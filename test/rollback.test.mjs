import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { root } from '../src/config.mjs';

test('rollback dry-run preserves process and rollback stops only its copied probe', { timeout: 30000 }, async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dot-rollback-'));
  fs.mkdirSync(path.join(dir, 'scripts')); fs.mkdirSync(path.join(dir, 'src'));
  fs.copyFileSync(path.join(root, 'scripts', 'rollback.ps1'), path.join(dir, 'scripts', 'rollback.ps1'));
  const source = path.join(dir, 'src', 'server.mjs');
  fs.writeFileSync(source, 'console.log("ready"); setInterval(() => {}, 1000);');
  const child = spawn(process.execPath, [source], { windowsHide: true });
  const closed = new Promise(resolve => child.once('close', resolve));
  t.after(async () => { if (child.exitCode === null) child.kill(); await closed; fs.rmSync(dir, { recursive: true, force: true }); });
  await new Promise(resolve => child.stdout.once('data', resolve));
  const args = ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.join(dir, 'scripts', 'rollback.ps1')];
  const dry = spawnSync('powershell.exe', [...args, '-DryRun'], { encoding: 'utf8', windowsHide: true });
  assert.equal(dry.status, 0, dry.stderr);
  assert.ok(dry.stdout.includes(`PID=${child.pid}`));
  assert.doesNotThrow(() => process.kill(child.pid, 0));
  const stop = spawnSync('powershell.exe', args, { encoding: 'utf8', windowsHide: true });
  assert.equal(stop.status, 0, stop.stderr);
  assert.ok(stop.stdout.includes(`Stopped owned process PID=${child.pid}`));
  await closed;
  assert.throws(() => process.kill(child.pid, 0));
  assert.ok(fs.existsSync(source));
});
